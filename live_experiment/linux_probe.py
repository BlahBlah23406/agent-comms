import os
import time

def read_loadavg():
    with open("/proc/loadavg", "r") as f:
        parts = f.read().strip().split()
        return {"1m": float(parts[0]), "5m": float(parts[1]), "15m": float(parts[2])}

def read_meminfo():
    mem = {}
    with open("/proc/meminfo", "r") as f:
        for line in f:
            if ":" in line:
                k, v = line.split(":", 1)
                val = v.strip().split()[0]
                mem[k.strip()] = int(val)
    total = mem.get("MemTotal", 1)
    avail = mem.get("MemAvailable", 0)
    used_pct = round((total - avail) / total * 100, 2)
    return {"total_mb": total // 1024, "available_mb": avail // 1024, "used_pct": used_pct}

def read_tcp_count():
    with open("/proc/net/tcp", "r") as f:
        lines = f.readlines()
        return max(0, len(lines) - 1)

def sample_metrics():
    return {
        "timestamp": time.time(),
        "load": read_loadavg(),
        "memory": read_meminfo(),
        "active_tcp_sockets": read_tcp_count(),
    }
